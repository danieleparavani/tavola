// Vocali accentate: la lettera piu il segno, cosi non serve ridisegnarle da capo.
const ACCENTS = {
  à: ['a', [[[0.34, -0.72], [0.2, -0.6]]]], è: ['e', [[[0.32, -0.72], [0.18, -0.6]]]],
  é: ['e', [[[0.18, -0.72], [0.32, -0.6]]]], ì: ['i', [[[0.24, -0.76], [0.1, -0.64]]]],
  ò: ['o', [[[0.34, -0.72], [0.2, -0.6]]]], ù: ['u', [[[0.34, -0.72], [0.2, -0.6]]]],
  À: ['A', [[[0.4, -0.88], [0.26, -0.78]]]], È: ['E', [[[0.38, -0.88], [0.24, -0.78]]]],
};

const SLANT = 0.16;

function glyphFor(ch) {
  if (G[ch]) return G[ch];
  const accented = ACCENTS[ch];
  if (accented) {
    const base = G[accented[0]];
    return { w: base.w, s: [...base.s, ...accented[1]] };
  }
  const lower = ch.toLowerCase();
  if (G[lower]) return G[lower];
  return G[' '];
}

export function measureText(text, size, tracking = 0.04) {
  let w = 0;
  for (const ch of String(text)) w += (glyphFor(ch).w + tracking) * size;
  return w;
}

// Scrive `text` con la linea di base in (x, y). Restituisce la larghezza occupata. Ogni lettera
// riceve uno scostamento minimo e stabile (dipende dal testo e dalla posizione, non dal caso),
// perche in una scrittura vera due "a" non sono mai identiche.
export function drawHandText(canvas, text, x, y, size, opts = {}) {
  const { color = [78, 70, 64], weight = 1, alpha = 0.72, seed = 1, tracking = 0.04, jitter = 1 } = opts;
  const strokes = [];
  let cursor = x;
  let i = 0;
  for (const ch of String(text)) {
    const glyph = glyphFor(ch);
    const n1 = valueNoise(i * 3.7 + 1, seed % 97, seed);
    const n2 = valueNoise(i * 3.7 + 40, seed % 97, seed + 5);
    const n3 = valueNoise(i * 2.3 + 80, seed % 97, seed + 9);
    const dx = (n1 - 0.5) * 0.03 * size * jitter;
    const dy = (n2 - 0.5) * 0.05 * size * jitter;
    const scale = 1 + (n3 - 0.5) * 0.06 * jitter;
    for (const stroke of glyph.s) {
      strokes.push(stroke.map(([gx, gy]) => [
        cursor + (gx - SLANT * gy) * size * scale + dx,
        y + gy * size * scale + dy,
      ]));
    }
    cursor += (glyph.w + tracking) * size;
    i++;
  }
  if (strokes.length) {
    drawInkBatch(canvas, strokes, color, {
      width: Math.max(1, size * 0.075 * weight), alpha, seed, wobble: size * 0.012, breaks: 0.03,
    });
  }
  return cursor - x;
}

// Manda a capo su parole intere, misurando davvero i glifi invece di contare i caratteri.
export function wrapText(text, size, maxWidth, tracking = 0.04) {
  const words = String(text).split(/\s+/).filter(Boolean);
  const lines = [];
  let current = '';
  for (const word of words) {
    const candidate = current ? `${current} ${word}` : word;
    if (current && measureText(candidate, size, tracking) > maxWidth) {
      lines.push(current);
      current = word;
    } else current = candidate;
  }
  if (current) lines.push(current);
  return lines;
}
